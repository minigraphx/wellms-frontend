import type { Translation } from "../types";

export type OrderStatus = "paid" | "cancelled" | "pending";

// The API sends an order status as a name or a number ("paid"/1, "cancelled"/3); anything else
// counts as pending. Look up the label with t.shop.orderStatus[orderStatusOf(order.status)].
export function orderStatusOf(status: string | number): OrderStatus {
  const s = String(status).toLowerCase();
  if (s === "paid" || s === "1") return "paid";
  if (s === "cancelled" || s === "3") return "cancelled";
  return "pending";
}

